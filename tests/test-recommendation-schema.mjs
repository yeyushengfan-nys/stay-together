import assert from 'node:assert/strict';
import {constrainedRecommendationSchema,recommendationSchema} from '../lib/hotel-ai.mjs';
const snapshot={hotels:[{id:'a',quoteBundle:{offers:[{}]}},{id:'b',quoteBundle:{offers:[{}]}},{id:'c'}]};
const checks=[{hotel_id:'a',blocked:[],unknown:['smart']},{hotel_id:'b',blocked:['breakfast'],unknown:[]},{hotel_id:'c',blocked:[],unknown:[]}];
let schema=constrainedRecommendationSchema(snapshot,checks);
assert.equal(schema.properties.recommendations.minItems,1);
assert.equal(schema.properties.recommendations.maxItems,1);
assert.deepEqual(schema.properties.recommendations.items.properties.hotel_id.enum,['c']);
assert.equal(schema.properties.offer_assessments.minItems,2);
assert.equal(schema.properties.offer_assessments.maxItems,2);
assert.deepEqual(schema.properties.offer_assessments.items.anyOf.map(s=>s.properties.hotel_id.enum[0]),['a','b']);
schema=constrainedRecommendationSchema(snapshot,checks.map(g=>({...g,unknown:['missing']})));
assert.equal(schema.properties.recommendations.maxItems,0);
assert.equal(schema.properties.recommendations.minItems,0);
schema=constrainedRecommendationSchema(snapshot,checks.map(g=>({...g,blocked:[],unknown:[]})));
assert.equal(schema.properties.recommendations.minItems,2);
assert.deepEqual(schema.properties.recommendations.items.properties.hotel_id.enum,['a','b','c']);
assert.equal(recommendationSchema.properties.recommendations.maxItems,undefined);
console.log('PASS output schema restricts recommendation count and IDs to eligible hotels; quotation coverage count is mandatory; base schema stays unchanged.');
