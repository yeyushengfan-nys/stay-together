const assert=require('node:assert/strict');
const vm=require('node:vm'),fs=require('node:fs');
const context={module:{exports:{}},Date};vm.runInNewContext(fs.readFileSync('./public/engine.js','utf8'),context);
const {rank,evaluate,factsFor}=context.module.exports;
const p={id:'p',name:'朋友',budget:650,budgetHard:true,requireSmart:true,requireLaundry:false,avoidMold:true,transitHard:false,maxMetro:10,weights:{price:5,transit:5,newness:2,facilities:2}};
const h={id:'h',name:'样本',price:580,metro:5,facts:{opened:2024,renovated:null,smart:true,laundry:true,mold:false},evidence:[]};
assert.equal(rank([h],[p]).top.length,1,'满足条件才推荐');
assert.equal(rank([{...h,price:700}],[p]).top.length,0,'硬预算不能被高偏好分抵消');
assert.equal(rank([{...h,facts:{...h.facts,smart:null}}],[p]).top.length,0,'必需设施未知时不当成满足');
assert.equal(rank([{...h,facts:{...h.facts,mold:true}}],[p]).top.length,0,'明确霉味反馈触发排除');
assert.equal(rank([h],[p,{...p,id:'p2',budget:400}]).top.length,0,'所有同行人的必要条件都要满足');
const conflict={...h,evidence:[{confirmed:true,claims:{smart:false}}]};
assert.equal(factsFor(conflict).facts.smart,null,'互相矛盾的依据保持待确认');
assert.equal(rank([conflict],[p]).top.length,0,'冲突不能被后来的资料覆盖');
assert.equal(evaluate({...h,evidence:[{confirmed:false,claims:{smart:false}}]},[p]).facts.smart,true,'未确认的识别结果不进入推荐');
assert.equal(rank([h,{...h,id:'h2'},{...h,id:'h3'}],[p]).top.length,2,'最多推荐两家');
assert.equal(rank([],[p]).top.length,0,'空候选正常处理');
assert.ok(Number.isFinite(evaluate(h,[{...p,weights:{price:0,transit:0,newness:0,facilities:0}}]).min),'所有偏好权重为0时可解释退化');
console.log('11项推荐规则检查通过');
